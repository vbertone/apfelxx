int main()
{
  constexpr bool display = false;
  std::vector<double> qTvals = {1.e-5, 2, 6, 24, 32};
  const double Qmin          = 66;
  const double Qmax          = 116;
  const double etamin        = -2.5;
  const double etamax        = +2.5;
  const double qTcut         = 27.;
  auto GenerateGrid          = [](int n, double min, double max, int ext = 0,
                                  bool lgt = false) -> std::vector<double>
  {
    std::vector<double> grid(n + ext + 1, 0.);
    if (lgt)
      {
        const double step = log(max / min) / n;
        for (int i = 0; i <= n + ext; i++) grid[i] = min * exp(i * step);
      }
    else
      {
        const double step = (max - min) / n;
        for (int i = 0; i <= n + ext; i++) grid[i] = min + i * step;
      }
    return grid;
  };

  const auto Qgrid  = GenerateGrid(10, Qmin, Qmax, 2);
  const auto xigrid = GenerateGrid(10, exp(0.), exp(2.5), 2, true);

  apfel::TwoBodyPhaseSpace ps{qTcut, etamin, etamax, 1.e-5};
  std::cout << std::setprecision(16) << std::scientific << std::showpos;
  size_t index = 0;
  double m = 0.;
  double m_der = 0.;
  for (const auto& Q : Qgrid)
    {
      for (const auto& xi : xigrid)
        {
          const double rap = std::log(xi);
          for (const auto& qT : qTvals)
            {
              {
                const double norm =  ( std::abs(_regression_data[index]) > 1.e-6 ) ? _regression_data[index] : 1;
                const double diff = (ps.PhaseSpaceReduction(Q, rap, qT) - _regression_data[index]) / norm;
                m = std::max(m, std::abs(diff));
                if (display)
                  std::cout << diff << "\n";
              }

              {
                const double norm =  ( std::abs(_derive_regression_data[index]) > 1.e-6 ) ? _derive_regression_data[index] : 1;
                const double diff = (ps.DerivePhaseSpaceReduction(Q, rap, qT) - _derive_regression_data[index]) / norm;
                m_der = std::max(m_der, std::abs(diff));
                if (display)
                  std::cout << diff << "\n";
              }
              index++;
            }
        }
    }

  std::cout <<  std::setprecision(4) << std::scientific << std::showpos;
  std::cout << "Max difference            " << m << std::endl;
  std::cout << "Max difference derivative " << m_der << std::endl;
}
